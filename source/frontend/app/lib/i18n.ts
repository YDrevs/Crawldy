/**
 * Переклад ключа. Порядок той самий, що на бекенді: потрібна мова, потім
 * англійська, потім сам ключ — щоб забутий рядок було видно, а не щоб він
 * зникав.
 */
export function translate(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const template = DICTS[locale]?.[key] ?? DICTS[FALLBACK_LOCALE]?.[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

/**
 * Множина.
 *
 * `Intl.PluralRules` — стандарт браузера, а не бібліотека: він знає, що
 * в англійській дві форми, в українській три, а в японській одна, і знає
 * це для всіх одинадцяти мов без жодного мегабайта даних CLDR.
 *
 * Ключі в словнику мають суфікс форми: `dash.affected.one`,
 * `dash.affected.other`. Якщо потрібної форми немає — беремо `other`:
 * забутий переклад має дати трохи незграбний рядок, а не порожнечу.
 *
 * Без цього виходить «1 pages» — дрібниця, яку помічають усі, і саме та
 * дрібниця, через яку продукт виглядає зробленим наспіх.
 */
export function plural(
  locale: Locale,
  key: string,
  count: number,
  params?: Record<string, string | number>,
): string {
  const form = new Intl.PluralRules(locale).select(count);
  const dict = DICTS[locale] ?? {};
  const fallback = DICTS[FALLBACK_LOCALE] ?? {};
  const template =
    dict[`${key}.${form}`] ??
    dict[`${key}.other`] ??
    fallback[`${key}.${form}`] ??
    fallback[`${key}.other`] ??
    key;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    if (name === "count") return String(count);
    return params && name in params ? String(params[name]) : whole;
  });
}

/**
 * Дата коротким форматом **мовою інтерфейсу**.
 *
 * `toLocaleDateString` без явної мови бере мову браузера, і на
 * англійському інтерфейсі виходило «13 вер.» — сторінка однією мовою, а
 * дата іншою. Мова інтерфейсу тут не збігається з мовою системи частіше,
 * ніж здається: людина ставить українську Windows і читає продукт
 * англійською.
 */
export function formatDate(locale: Locale, iso: string): string {
  return new Date(iso).toLocaleDateString(locale, { day: "numeric", month: "short" });
}

