export const FALLBACK_LOCALE: Locale = "en";

/**
 * Мови з ПОВНИМ каталогом кабінету. Решта падала б у фолбек.
 *
 * До 8 вересня 2026 тут стояло `["en", "uk"]`, і це був чесний
 * запобіжник, а не обмеження дизайну: у німецькому, іспанському та
 * французькому словниках було по 137 ключів проти 382 англійських, тож
 * увімкнена «de» дала б наполовину англійський інтерфейс. Тепер бракує
 * нуля в кожній із шести — тому перелік і розширено.
 *
 * Список тримається окремо від `PUBLIC_SITE_LOCALES` навмисно: сайт і
 * кабінет — різні поверхні, і мова може зʼявитися на одній раніше, ніж
 * на іншій. Повноту стереже тест, а не ця константа.
 */
export const COMPLETE_LOCALES: Locale[] = ["en", "de", "es", "fr", "ru", "uk"];

/** Мови, якими написаний публічний сайт. Ширше за мови кабінету. */
export const PUBLIC_SITE_LOCALES: Locale[] = ["en", "de", "es", "fr", "ru", "uk"];

/**
 * Мова сайту з сирого значення адреси — або нічого.
 *
 * Не мова ФОРМИ: німецький відвідувач на сторінці входу бачить
 * англійську форму (каталогу de в кабінеті немає), але сайт для нього
 * лишається німецьким, і дорога назад мусить вести на /de. Саме тому
 * значення перевіряється проти шести мов сайту, а не двох мов кабінету.
 */
export function asSiteLocale(raw: string | null): Locale | null {
  return raw && (PUBLIC_SITE_LOCALES as string[]).includes(raw)
    ? (raw as Locale)
    : null;
}

/**
 * Адреса головної цією мовою. Обрана мова живе в префіксі шляху, тож
 * «повернутися на головну» без префікса означає мовчки перемкнути
 * людину на англійську — рівно та втрата, якої тут не існує.
 */
export function publicHomeHref(locale: Locale): string {
  return locale === "en" ? "/" : `/${locale}`;
}

/**
 * Адреса екрана продукту цією мовою.
 *
 * Екрани продукту (`/login`, `/forgot`, `/reset`) префікса мови в шляху
 * не мають — мова їде параметром. Правило те саме, що для гостьового
 * результату: англійська без параметра, решта з `?lang=`. Помилка, якої
 * воно уникає, вже траплялася: `ctaOf` віддавав `?lang=uk` лише для
 * української, і німець із німецької сторінки отримував англійський
 * екран не тому, що перекладу не було, а тому, що адреса його не
 * просила.
 */
export function productHref(path: string, locale: Locale): string {
  return locale === "en" ? path : `${path}?lang=${locale}`;
}

/**
 * Дописати підпис про подію до адреси, яка вже може мати параметр мови.
 *
 * Склеювати через `?` наосліп не можна: `/login?lang=uk?notice=reset` —
 * це один параметр із дивним значенням, а не два.
 */
export function withNotice(href: string, notice: string): string {
  return `${href}${href.includes("?") ? "&" : "?"}notice=${notice}`;
}

