/**
 * Чотири різні набори мов, які всі звуться «мови».
 *
 * Досі їх було два, і вони випадково збігалися — обидва дорівнювали
 * `["en", "uk"]`. Щойно публічний сайт виходить шістьма мовами, збіг
 * зникає, і кожне питання «якою мовою?» отримує свою відповідь:
 *
 * 1. **`Locale`** (у `contracts.ts`) — мови, які взагалі існують як тип.
 *    Це те, що система вміє прийняти в запиті й зберегти в профілі.
 * 2. **`RELEASED_LOCALES`** — мови, якими є **вміст публічного сайту**.
 *    Лише вони потрапляють у перемикач, у `hreflang` і в карту сайту.
 * 3. **`APP_LOCALES`** — мови, якими перекладено інтерфейс кабінету.
 *    Тут фолбек в англійську допустимий: незнайомий рядок у кнопці —
 *    прогалина перекладу, і людина це розуміє.
 * 4. **Каталог знахідок** (на бекенді, `i18n.COMPLETE_LOCALES`) — мови,
 *    якими написані самі знахідки. Найдорожчий набір — локалізовані
 *    тексти перевірок.
 *
 * Плутати 2 і 3 особливо небезпечно. Публічна сторінка, що показує
 * англійський текст під німецькою адресою, — це вже не прогалина
 * перекладу, а дублікат чужою мовою, який пошук справедливо покарає.
 * Тому стратегія прямо забороняє публікувати таку сторінку, а не просто
 * не радить.
 */

import type { Locale } from "./contracts";

/**
 * Мови публічного сайту.
 *
 * Мова потрапляє сюди тоді, коли для неї існує **вміст**, а не код.
 * Порядок — той, у якому вони показуються в перемикачі: спершу
 * англійська як загальна, далі за абеткою власної назви.
 */
export const RELEASED_LOCALES: Locale[] = ["en", "de", "es", "fr", "ru", "uk"];

/** Мови з перекладеним інтерфейсом кабінету. */
export const APP_LOCALES: Locale[] = ["en", "uk"];

/**
 * Мова, яка живе в корені без префікса.
 *
 * `/` замість `/en/`. Це рішення не косметичне: воно означає, що
 * англійська адреса не має дубля з префіксом, тож canonical у неї один.
 */
export const ROOT_LOCALE: Locale = "en";

/** Мова, якою підставляється те, чого немає. Ніколи не українська. */
export const FALLBACK: Locale = "en";

export function isReleased(value: string): value is Locale {
  return (RELEASED_LOCALES as string[]).includes(value);
}

/**
 * Префікс адреси для мови.
 *
 * Порожній для кореневої: `/website-audit`, а не `/en/website-audit`.
 */
export function prefixOf(locale: Locale): string {
  return locale === ROOT_LOCALE ? "" : `/${locale}`;
}
