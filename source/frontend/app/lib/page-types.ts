/**
 * Модель публічної сторінки: одна сутність, багато мов.
 *
 * ## `page_key` — не слаг і не переклад слага
 *
 * Сторінка «аудит сайту» — це одна річ, у якої шість адрес. Німецька
 * зветься `website-check`, іспанська `auditoria-web`, російська
 * `proverka-sajta` — і це не переклади англійського `website-audit`, а
 * окремі пошукові наміри, взяті з матриці. Спроба вивести один слаг з
 * іншого правилом транслітерації дала б адреси, яких ніхто не шукає.
 *
 * Звʼязок між ними тримає `page_key`. З нього ж виводиться `hreflang` —
 * автоматично, а не руками.
 *
 * ## Сторінка існує в мові тоді, коли існує її вміст
 *
 * `locales` — не перелік «куди ми плануємо перекласти», а перелік того,
 * що написане. Мови немає в цьому обʼєкті — сторінки в ній не існує:
 * її немає ані в перемикачі, ані в `hreflang`, ані в карті сайту, і
 * звернення до її адреси дає 404.
 *
 * Це прямо з вимоги стратегії: англійський текст під німецькою адресою
 * — не прогалина перекладу, а дублікат чужою мовою. Один обʼєкт замість
 * двох (метадані окремо, вміст окремо) саме тому: два джерела правди
 * розійшлися б, і розійшлися б мовчки.
 */

import type { ComponentType } from "react";

import type { Locale } from "./contracts";

/**
 * Стабільний ідентифікатор сторінки. Ніколи не перекладається й ніколи
 * не міняється — на ньому тримаються `hreflang`, перелінковка й
 * хлібні крихти.
 */
export type PageKey =
  // ── комерційне ядро ────────────────────────────────────────────────
  | "home"
  | "ai_visibility"
  | "website_audit"
  | "seo_audit"
  | "geo_audit"
  | "technical_seo_audit"
  // ── довіра ─────────────────────────────────────────────────────────
  | "methodology"
  | "pricing"
  | "about"
  | "contact"
  // ── правова інформація ─────────────────────────────────────────────
  | "legal_privacy"
  | "legal_terms"
  | "legal_refunds"
  | "legal_acceptable_use";

/**
 * До якої частини сайту належить сторінка. Керує навігацією й підвалом.
 *
 * `materials` — сторінки, що пояснюють окремі частини ОДНІЄЇ перевірки
 * Crawldy (видимість у ШІ, SEO-аудит, технічний аудит). У колонці
 * «Продукт» вони читались як окремі продукти — погоджена архітектура
 * футера виносить їх в окрему колонку «Матеріали».
 */
/**
 * `legal` — окрема колонка підвалу, а не частина «Компанії».
 * Юридичні документи не пояснюють продукт: їх шукають тоді, коли
 * треба знайти умови, і тримати їх серед сторінок про компанію
 * означало б ховати саме те, що мусить бути постійно доступним.
 */
export type PageGroup = "product" | "materials" | "company" | "legal";

/**
 * Роль сторінки в структурованих даних.
 *
 * `WebPage` — звичайна сторінка. `TechArticle` — технічний матеріал для
 * розробників. `Offer` тримається окремо, бо ціни зʼявляться лише після
 * рішення про разову покупку, і поки їх немає, розмітки з цінами бути не
 * має теж.
 */
export type SchemaRole = "web_page" | "tech_article" | "pricing" | "contact";

export interface LocalizedPage {
  /**
   * Адреса в межах мови, без префікса мови й без слагів батьків.
   * Порожній рядок — головна.
   */
  slug: string;
  /** `<title>`. Роль — виграти клік у видачі, а не повторити H1. */
  title: string;
  /** `<h1>`. Роль — підтвердити людині, що вона там, куди йшла. */
  h1: string;
  /** `<meta name="description">`. */
  description: string;
  /** Підпис у меню й підвалі. Коротший за H1. */
  navLabel: string;
  /** Тіло сторінки. */
  Body: ComponentType;
}

export interface PageDefinition {
  key: PageKey;
  group: PageGroup;
  /** Батьківська сторінка: дає вкладену адресу й хлібні крихти. */
  parent?: PageKey;
  schema: SchemaRole;
  /**
   * Місце в **підвалі**. Відсутнє — сторінка є, але в переліках її немає:
   * до неї ведуть посилання з тексту сусідніх сторінок.
   */
  navOrder?: number;
  /**
   * Чи показувати сторінку ще й у шапці.
   *
   * Окремо від підвалу навмисно. Підвал може дозволити собі перелік;
   * шапка — ні: девʼять пунктів у ній перестають бути навігацією й
   * стають стіною, у якій нічого не знайти.
   *
   * Є й друга причина, і вона з нашого ж двигуна: посилання, що стоїть
   * на кожній сторінці, не каже про жодну. Тематичний звʼязок несуть
   * блоки «читайте також» у тексті, а не шапка.
   */
  inHeader?: boolean;
  /**
   * Мови, якими сторінка **написана**. Не плани, а факт.
   */
  locales: Partial<Record<Locale, LocalizedPage>>;
}
