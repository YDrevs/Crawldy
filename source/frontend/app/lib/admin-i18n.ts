const DICTS: Record<AdminLocale, Dict> = { uk, en };

/** Рядок мовою адміністратора; невідомий ключ повертає сам ключ. */
export function adminText(
  locale: AdminLocale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (!params) return raw;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    raw,
  );
}

/** Початкова мова: збережений вибір, інакше профіль, інакше англійська. */
export function initialAdminLocale(profileLocale: string | undefined): AdminLocale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "uk" || stored === "en") return stored;
  } catch {
    /* приватне вікно чи заблоковане сховище — не привід падати */
  }
  return profileLocale === "uk" ? "uk" : "en";
}

export function rememberAdminLocale(locale: AdminLocale): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* те саме */
  }
}

/** Ключі обох словників — для тесту паритету. */
export function adminKeys(locale: AdminLocale): string[] {
  return Object.keys(DICTS[locale]);
}
