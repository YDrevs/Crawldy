"use client";

/**
 * Мова САЙТУ, коли адреси з нею поруч немає.
 *
 * На публічних сторінках мова живе в префіксі шляху (`/de/pricing`), і
 * цього досить. У кабінеті префікса немає взагалі: там мову інтерфейсу
 * задає профіль, а профіль знає лише мови, якими кабінет існує (en, uk).
 * Через це дорога назад на сайт для німця, іспанця, француза й росіянина
 * вела на англійську головну — не тому, що ми її загубили при виході, а
 * тому, що при вході не було де її тримати.
 *
 * Тут вона й тримається: останню публічну сторінку памʼятає браузер.
 * Це підказка для навігації, а не налаштування — тому localStorage, а не
 * профіль: інакше вибір мови сайту на чужому ноутбуці перемикав би мову
 * кабінету, а вона вибирається окремо й свідомо.
 *
 * Читання й запис захищені try/catch: приватне вікно й заблоковані дані
 * сайту кидають виняток на самому зверненні до сховища.
 */

import { useEffect, useState } from "react";

import type { Locale } from "./contracts";
import { asSiteLocale } from "./i18n";

export const SITE_LOCALE_KEY = "crawldy_site_locale";

export function rememberSiteLocale(locale: Locale): void {
  try {
    window.localStorage.setItem(SITE_LOCALE_KEY, locale);
  } catch {
    // Сховище недоступне — дорога назад просто впаде на запасний варіант.
  }
}

export function readSiteLocale(): Locale | null {
  try {
    return asSiteLocale(window.localStorage.getItem(SITE_LOCALE_KEY));
  } catch {
    return null;
  }
}

/**
 * Мова сайту для посилань кабінету: мова профілю, далі — остання
 * публічна сторінка, далі — англійська.
 *
 * Порядок саме такий, і спершу він був зворотний. Памʼять браузера
 * перемагала профіль, тож власник з українським кабінетом натискав знак
 * і потрапляв на англійську головну — просто тому, що колись у цьому
 * браузері відкривав англійську сторінку. Профіль — свідомий вибір
 * людини й живе довше за випадковий візит, тож він головніший.
 *
 * Памʼять лишається потрібною для мов, яких у профілі бути не може:
 * кабінет говорить двома мовами, сайт шістьма, і в німця з /de профіль
 * порожній. Для нього виграє памʼять — і дорога назад веде на /de.
 *
 * Значення зі сховища береться в ефекті, а не в початковому стані: на
 * сервері localStorage не існує, і читання під час рендеру дало б
 * розбіжність розмітки при гідратації.
 */
export function useSiteLocale(profile?: string | null): Locale {
  const chosen = asSiteLocale(profile ?? null);
  const [locale, setLocale] = useState<Locale>(chosen ?? "en");
  useEffect(() => {
    setLocale(chosen ?? readSiteLocale() ?? "en");
  }, [chosen]);
  return locale;
}
