/**
 * Намір купити, записаний в адресу сторінки оплати.
 *
 * Сторінка цін не відкриває касу сама: вона лише називає, що купують, і
 * веде на `/checkout`. Там намір перетворюється на транзакцію провайдера
 * — з входом, якщо він потрібен, і без жодної зупинки в кабінеті.
 *
 * Окремим модулем, а не в самій сторінці: сторінка Next не має права
 * експортувати нічого, крім компонента й службових полів, — інакше
 * збірка падає на перевірці типів маршруту.
 */

export interface BuyIntent {
  /** `offer` — разова покупка або пакет, `plan` — підписка. */
  kind: "offer" | "plan";
  code: string;
}

/**
 * Намір із рядка запиту. `null` — його немає, і сторінка обслуговує
 * інший вхід: `?_ptxn=` від Paddle або нічого.
 *
 * Порожнє значення (`?offer=`) — це не намір: код пропозиції порожнім не
 * буває, а відкривати касу «невідомо чого» гірше, ніж сказати, що платити
 * тут нема за що.
 */
export function intentFrom(search: string): BuyIntent | null {
  const params = new URLSearchParams(search);
  const offer = (params.get("offer") ?? "").trim();
  if (offer) return { kind: "offer", code: offer };
  const plan = (params.get("plan") ?? "").trim();
  if (plan) return { kind: "plan", code: plan };
  return null;
}

/**
 * Адреса каси для цього наміру. Мова їде в адресі, бо екран оплати
 * говорить усіма шістьма мовами сайту, а англійська лишається без
 * параметра — те саме правило, що на гостьовому екрані результату.
 */
/**
 * Куди повертатися після оплати цього наміру.
 *
 * Завжди в кабінет: через цю сторінку купують те, що лягає на баланс, —
 * пакет і підписку. Разова перевірка сюди не приходить взагалі: вона
 * анонімна й живе у власній воронці (`/buy`), де сайт питають ПІСЛЯ
 * оплати й без жодної реєстрації (рішення власника 2026-09-06).
 */
export function afterPayment(_intent: BuyIntent): string {
  return "/app/plan";
}

export function checkoutHref(intent: BuyIntent, locale: string): string {
  const query = `${intent.kind}=${encodeURIComponent(intent.code)}`;
  return locale === "en" ? `/checkout?${query}` : `/checkout?${query}&lang=${locale}`;
}
