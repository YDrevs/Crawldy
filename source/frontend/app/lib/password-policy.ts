/**
 * Мінімальна довжина нового пароля — одне число на весь інтерфейс.
 *
 * Модуль існує рівно тому, що до 25 вересня 2026 це число жило в
 * пʼятьох місцях і казало три різні речі: `MIN_LENGTH` бекенда — 10,
 * дві константи `MIN_PASSWORD` на екранах і літерал у формі входу — 12,
 * а схема гостьового привласнення (`ClaimIn`) — 8.
 *
 * Розбіжність вважалася безпечною: усе, що проходило форму, проходило й
 * сервер. Насправді вона вже коштувала дефекту. Пароль на 8–11 символів
 * проходив схему привласнення, падав у домені на політиці, і маршрут
 * його не ловив — клієнт діставав 500 на власну одруківку. Слабший бік
 * оголошував правило, і оголошував його помилкою сервера.
 *
 * Тепер число одне тут і одне в `app/identity/passwords.py`, а розійтися
 * їм не дає тест бекенда `test_password_policy.py`: він читає цей
 * файл і валиться, якщо сторони розминулися. Та сама межа, що стереже
 * знімок ваг скорингу для публічної сторінки методології.
 *
 * Текст правила («Щонайменше 12 символів») живе в каталозі шістьма
 * мовами під ключем `auth.passwordHint`; той самий тест перевіряє, що в
 * кожній із шести стоїть саме це число.
 */
export const MIN_PASSWORD_LENGTH = 12;
