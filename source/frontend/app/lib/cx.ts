/**
 * Склеїти класи, відкинувши порожні.
 *
 * Живе окремо від примітивів навмисно. Примітиви позначені `"use client"`,
 * і все, що з них експортується, стає клієнтським — включно з чистою
 * функцією без стану. Серверний компонент, який покликав таку функцію,
 * падає з «Attempted to call cx() from the server», і виглядає це як
 * помилка в компоненті, а не як наслідок директиви на початку файлу.
 *
 * `unknown` в аргументах: у виразах на кшталт `error && "…"` тип `error`
 * буває `ReactNode`, і вузька сигнатура змушувала б писати `!!error &&`
 * по всьому коду — тобто боротися з типами замість того, щоб ними
 * користуватися.
 */
export function cx(...parts: unknown[]): string {
  return parts
    .filter((part): part is string => typeof part === "string" && part !== "")
    .join(" ");
}
