import { Manrope } from "next/font/google";

import "./globals.css";

/**
 * Спільна оболонка документа для двох коренів.
 *
 * Коренів у застосунку два — публічний сайт і кабінет, — бо мова в них
 * розвʼязується по-різному: на публічних сторінках вона в адресі й має
 * бути видимою пошуковику, у кабінеті йде з профілю людини. Спільним у
 * них лишається сам документ: гарнітура, класи `body`, підключення
 * стилів. Дублювати це двічі означає одного дня змінити шрифт лише в
 * половині продукту.
 *
 * ## Гарнітура
 *
 * Manrope — геометрична, з ледь заокругленими закінченнями: під характер
 * знака, у якому круглим є все. Змінна вага одним файлом, тож чотири
 * накреслення не коштують чотирьох завантажень.
 *
 * Латиниця й кирилиця звідси. Арабська, деванагарі, китайська та
 * японська йдуть системними шрифтами далі в стеку (`tokens.css`):
 * браузер бере першу гарнітуру, що містить символ, тож японська
 * сторінка не тягне зайвих мегабайтів, а латиниця не зʼїжджає на
 * системний шрифт. Одна декоративна гарнітура на всі писемності —
 * найшвидший спосіб зробити половину мов гіршими за решту.
 *
 * `display: swap` — текст видно одразу системним шрифтом, поки
 * вантажиться основний. Порожній екран заради «правильного» шрифту
 * коштує дорожче за коротку підміну.
 */
const manrope = Manrope({
  subsets: ["latin", "latin-ext", "cyrillic", "cyrillic-ext"],
  weight: ["400", "500", "600", "700"],
  display: "swap",
  variable: "--font-manrope",
});

export function Document({
  lang,
  dir = "ltr",
  children,
}: {
  lang: string;
  dir?: "ltr" | "rtl";
  children: React.ReactNode;
}) {
  return (
    <html lang={lang} dir={dir} className={manrope.variable}>
      <body className="bg-background text-primary antialiased">{children}</body>
    </html>
  );
}
