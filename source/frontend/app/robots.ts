import type { MetadataRoute } from "next";

import { ORIGIN } from "./lib/entity";

/**
 * Політика краулерів — три різні рішення, а не одне.
 *
 * ## 1. Пошук
 *
 * Googlebot, Bingbot і решта класичних пошукових ботів — відкрито.
 * Кабінет закритий: приватні дані аудитів не мають потрапляти в пошук
 * ані сторінкою, ані шматком тексту в сніпеті.
 *
 * ## 2. AI, що відповідає на питання
 *
 * `OAI-SearchBot`, `PerplexityBot` та подібні читають сайт, щоб
 * послатися на нього у відповіді. Це та сама видимість, заради якої
 * існує пошук, — відкрито.
 *
 * ## 3. AI, що навчається
 *
 * `GPTBot`, `CCBot` збирають вміст у навчальні набори. Це не приносить
 * ані трафіку, ані згадки — заборонено.
 *
 * ## `Google-Extended` окремо від усього
 *
 * Він не керує ані Google Search, ані потраплянням в індекс: його
 * заборона не коштує жодної позиції у видачі. Тому це власна вісь, а не
 * частина пошукової політики, і плутати їх — типова помилка, яка коштує
 * сайтам видимості в пошуку без жодної потреби.
 *
 * Керує він двома речами одразу: використанням вмісту у відповідях
 * Gemini **і** в навчанні майбутніх моделей Google. Відокремити перше
 * від другого цим перемикачем неможливо, а наше правило про навчання
 * однозначне — заборонено. Тому заборонено й тут.
 *
 * Прапорець лишається окремим саме тому, що Google може розділити ці
 * дві речі пізніше: тоді зміниться одне значення, а не архітектура.
 */

/** Боти, які читають сайт, щоб послатися на нього у відповіді. */
const ANSWER_ENGINES = ["OAI-SearchBot", "PerplexityBot", "Applebot-Extended"];

/**
 * Боти, які збирають вміст у навчальні набори.
 *
 * `ClaudeBot` — чинний навчальний краулер Anthropic, і донедавна його тут
 * не було: групу закривав лише `anthropic-ai`, токен, якого в документації
 * Anthropic уже немає. Правило про навчання діяло на папері, а сайт
 * віддавався за wildcard. `Claude-SearchBot` і `Claude-User` лишаються
 * відкритими навмисно — це пошук і запит людини, тобто та сама видимість,
 * заради якої існує пошукова політика.
 */
const TRAINING_ONLY = [
  "GPTBot",
  "CCBot",
  "anthropic-ai",
  "Bytespider",
  "ClaudeBot",
];

/**
 * Окрема вісь: використання вмісту в AI-продуктах Google.
 * Не впливає ні на Google Search, ні на індексацію.
 */
const GOOGLE_AI_GROUNDING = "Google-Extended";
const ALLOW_GOOGLE_AI_GROUNDING = false;

// Гостьові результати й куплені звіти — приватні сторінки конкретних
// людей: краулерам там нема чого робити, а токен в адресі не має
// потрапляти в жоден індекс. Мета-noindex на них уже стоїть (група
// product), але robots дешевше зупиняє чемних роботів ще до запиту.
const PRIVATE = ["/app", "/admin", "/api", "/result", "/report"];

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      { userAgent: "*", allow: "/", disallow: PRIVATE },
      ...ANSWER_ENGINES.map((userAgent) => ({
        userAgent,
        allow: "/",
        disallow: PRIVATE,
      })),
      {
        userAgent: GOOGLE_AI_GROUNDING,
        ...(ALLOW_GOOGLE_AI_GROUNDING
          ? { allow: "/", disallow: PRIVATE }
          : { disallow: "/" }),
      },
      ...TRAINING_ONLY.map((userAgent) => ({ userAgent, disallow: "/" })),
    ],
    sitemap: `${ORIGIN}/sitemap.xml`,
    host: ORIGIN,
  };
}
