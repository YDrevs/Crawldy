/**
 * Структуровані дані сторінки.
 *
 * Окремим компонентом, бо цей самий чек ми продаємо: розмітка сутностей
 * — не «для SEO», а відповідь на питання «хто це і що воно робить», яку
 * AI-система інакше складає з випадкових шматків тексту.
 *
 * Виводиться в готовому HTML, а не додається скриптом: розмітка, що
 * зʼявляється після виконання JavaScript, для багатьох AI-краулерів не
 * існує взагалі.
 */
export function JsonLd({ graph }: { graph: object }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(graph) }}
    />
  );
}
