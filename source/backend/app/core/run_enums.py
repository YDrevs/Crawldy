"""Словник **запуску** аудиту, не двигуна.

`FailureClass` і `QuotaState` описують не те, що двигун міряє, а те, що з
його запуском сталося в продукті: чому він не дав результату і що з цього
випливає для рахунку. Двигун про них не знає й не має знати.

Лежать у `core`, бо в них немає власника серед контекстів: їх однаково
читають персистентність (колонки аудиту), білінг (політика повернення) і
продуктовий шар (класифікатор). Покласти їх у будь-який із трьох означало
б зробити два інші від нього залежними.
"""

from __future__ import annotations

from enum import StrEnum


class FailureClass(StrEnum):
    """Чому аудит не дав результату. Поле, а не розбір тексту помилки.

    Це факт, а не рішення. Чи повертати за нього гроші, вирішує
    `billing.refund_policy` — і може змінити це, не чіпаючи ні цей
    словник, ні машину станів квоти.

    Зіставляти рядок `error` мовою — шукати халепи; цей проєкт уже має
    таке правило для деградацій, і тут воно те саме.
    """

    # Сайт клієнта не відповів: DNS, TLS, таймаут, ланцюг редиректів.
    SITE_UNREACHABLE = "site_unreachable"
    # Сайт відповів відмовою: 403/429 на все. Це його рішення.
    SITE_BLOCKED = "site_blocked"
    # Зовнішній провайдер (PSI, браузер, модель) недоступний.
    #
    # Оголошений, але поки що не породжується жодним шляхом: провайдери
    # ловлять власні збої й віддають деградацію, бо аудит без Core Web
    # Vitals лишається аудитом. Значення лишається в словнику, щоб
    # політики (повторів, повернення квоти) вже були правильні на день,
    # коли збій провайдера справді долетить до рівня запуску.
    PROVIDER_FAILED = "provider_failed"
    # Виняток у нашому коді або недоступна інфраструктура.
    INTERNAL_ERROR = "internal_error"
    # Скасовано до виконання.
    CANCELLED = "cancelled"


class QuotaState(StrEnum):
    """Що сталося зі списаною одиницею квоти.

    Резервування при створенні — правильне: воно атомарне й закриває
    гонку. Але резерв мусить мати долю, інакше «списали й забули»
    перетворюється на «клієнт заплатив за нашу поломку».
    """

    RESERVED = "reserved"
    CONSUMED = "consumed"
    RELEASED = "released"


class QuotaSource(StrEnum):
    """З чого оплачено цей аудит.

    Записується, а не виводиться. Спокуса вивести є: якщо повернення
    кредиту не оновило жодного рядка, значить платили квотою. Але це
    висновок із відсутності, а він однаково виглядає і тоді, коли
    кредит просто загубився. Питання «чим це оплачено» надто дороге,
    щоб відповідати на нього здогадом.

    Порожньо — аудит, створений до появи разових покупок.
    """

    # Квота, включена в тарифний період.
    SUBSCRIPTION = "subscription"
    # Окремо куплений кредит без періоду.
    ONE_OFF = "one_off"
    # Безкоштовне превʼю: комерційні лічильники не торкаються взагалі.
    # Це рішення продукту, а не пільга тарифу: превʼю необмежені і в
    # гостя, і в акаунта, а від зловживання боронить технічний ліміт
    # частоти — окремий від прав шар. Довжина значення ≤ "subscription",
    # тож колонка VARCHAR не потребує міграції.
    FREE_PREVIEW = "free_preview"
    # Службовий тест команди: жодного резерву, жодного продажу, жодного
    # лічильника клієнта. Аналітика виключає ці аудити за цим значенням.
    ADMIN_TEST = "admin_test"
