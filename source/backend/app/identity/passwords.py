"""Паролі: хешування й перевірка.

Окремий модуль, щоб алгоритм можна було замінити в одному місці. Це не
теоретична обережність — параметри argon2 з часом підвищують, і в день,
коли це знадобиться, треба буде змінити рядок тут, а не шукати виклики
по кодовій базі.
"""

from __future__ import annotations

from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerifyMismatchError

# Параметри за замовчуванням від argon2-cffi відповідають рекомендаціям
# OWASP для argon2id. Піднімати їх свідомо — і разом із `needs_rehash`,
# який переведе наявні паролі на нові параметри при першому вході.
_hasher = PasswordHasher()

# Нижня межа довжини. Не «складність із трьох класів символів»: правила
# складності женуть людей до `Password1!`, тоді як довжина працює.
#
# Дванадцять, а не десять. До 25 вересня 2026 тут стояло 10, тоді як
# інтерфейс просив 12 — розбіжність була безпечна в цей бік (усе, що
# проходило форму, проходило й сервер), але означала, що правило
# продукту оголошує форма, а не сервер: те саме число жило у двох
# місцях, і меншим з них можна було скористатися повз форму, прямо
# через API. Тепер межа одна, і вона тут.
#
# Межа стосується ЛИШЕ нових паролів. Наявні хеші не чіпаються й не
# знецінюються: людина з десятисимвольним паролем входить, як і раніше
# (див. `rehash_existing`).
MIN_LENGTH = 12

# Верхня межа існує, щоб мегабайтний «пароль» не став способом завантажити
# процесор хешуванням.
MAX_LENGTH = 256


class WeakPassword(ValueError):
    """Пароль не проходить мінімальні вимоги."""


def validate(password: str) -> None:
    if len(password) < MIN_LENGTH:
        raise WeakPassword(f"пароль коротший за {MIN_LENGTH} символів")
    if len(password) > MAX_LENGTH:
        raise WeakPassword(f"пароль довший за {MAX_LENGTH} символів")


def hash_password(password: str) -> str:
    """Хеш НОВОГО пароля. Політика перевіряється тут і лише тут."""
    validate(password)
    return _hasher.hash(password)


def rehash_existing(password: str) -> str:
    """Перехешувати ВЖЕ ПРИЙНЯТИЙ пароль новими параметрами argon2.

    Політики тут немає навмисно, і це не послаблення — це єдиний спосіб
    підняти межу, нікого не замкнувши.

    Пастка, яку ця функція знімає, спрацьовує з відстроченням. Вхід
    перехешовує пароль, коли `needs_rehash` каже, що хеш зроблено
    слабшими параметрами. Поки перехешування йшло через
    `hash_password`, воно ще й ПЕРЕВІРЯЛО довжину — і в день, коли
    параметри argon2 підняли б, людина з десятисимвольним паролем,
    ввівши його ПРАВИЛЬНО, дістала б `WeakPassword` із глибини входу.
    Не «оновіть пароль», а помилка сервера на коректних даних, і саме в
    того, хто нічого не робив.

    Зараз це не вистрілило б лише тому, що параметри давно ті самі.
    Дефект, який чекає на не пов'язану з ним зміну, — найдорожчий: до
    моменту, коли він спрацює, причину вже ніхто не згадає.
    """
    return _hasher.hash(password)


def verify(password_hash: str, password: str) -> bool:
    """Чи підходить пароль. Будь-яка помилка розбору хеша — це «ні».

    Виняток тут означав би, що зіпсований рядок у базі валить вхід із
    500 замість 401 і показує стороннім, що з акаунтом щось не так.
    """
    try:
        return _hasher.verify(password_hash, password)
    except (VerifyMismatchError, InvalidHashError, ValueError):
        return False


def needs_rehash(password_hash: str) -> bool:
    """Чи хеш зроблено слабшими параметрами, ніж поточні."""
    try:
        return _hasher.check_needs_rehash(password_hash)
    except (InvalidHashError, ValueError):
        return True
