"""Словник контексту ідентичності.

Листовий модуль без залежностей — його імпортують і доменні сервіси, і
таблиці. Та сама причина, з якої `app/audit/enums.py` живе окремо від
моделей: спільний словник не має належати ні тому, хто ним користується,
ні тому, хто його зберігає.
"""

from __future__ import annotations

from enum import StrEnum


class Role(StrEnum):
    """Роль користувача в організації.

    Enum, а не таблиця з довільними дозволами. Таблиця ролей — це
    enterprise-складність наперед: вона додає join до кожної перевірки й
    вимагає інтерфейсу керування, якого на запуску нікому не потрібно.
    Три ролі покривають те, що є: власника, того, хто керує роботою, і
    того, хто нею користується.

    Розширити enum — це міграція на один рядок. Коли знадобляться
    кастомні дозволи, `role` стане зовнішнім ключем, і це буде адитивна
    зміна, а не перебудова.
    """

    OWNER = "owner"
    ADMIN = "admin"
    MEMBER = "member"

    @property
    def rank(self) -> int:
        """Порядок старшинства. Потрібен для «не нижче ніж» у перевірках."""
        return _RANK[self]

    def at_least(self, required: Role) -> bool:
        return self.rank >= required.rank


_RANK: dict[Role, int] = {Role.MEMBER: 0, Role.ADMIN: 1, Role.OWNER: 2}


class UserStatus(StrEnum):
    """Стан облікового запису.

    `PENDING` — зареєстрований, пошта не підтверджена. Він не блокує
    роботу: змушувати людину підтвердити пошту до першого аудиту означає
    втрачати її на порожньому екрані. Підтвердження знадобиться там, де
    ціна помилки вища — зміна пошти, запрошення в чужу організацію.
    """

    PENDING = "pending"
    ACTIVE = "active"
    DISABLED = "disabled"

    @property
    def can_sign_in(self) -> bool:
        return self is not UserStatus.DISABLED


class PlatformRole(StrEnum):
    """Роль **у платформі**, а не в організації.

    Окрема вісь навмисно, і це не педантизм. `Role` відповідає на питання
    «що ця людина може у своїй організації»; `PlatformRole` — на питання
    «чи вона взагалі з команди Crawldy». Змішати їх в одному enum означало
    б, що власник будь-якої організації на один крок від нашої адмінки, і
    крок цей — рядок у базі.

    Порожньо (`None` в колонці) — звичайний клієнт. Це дефолт для всіх, і
    саме тому вісь безпечна: щоб стати персоналом, потрібна явна дія, а не
    відсутність заборони.

    Два рівні, а не один прапорець: `STAFF` дивиться й допомагає,
    `ADMIN` міняє (індивідуальні умови, повтор подій білінгу). Розділити
    їх пізніше було б міграцією з розбором того, хто що вже встиг.
    """

    STAFF = "staff"
    ADMIN = "admin"

    @property
    def rank(self) -> int:
        return _PLATFORM_RANK[self]

    def covers(self, needed: PlatformRole) -> bool:
        """Чи цієї ролі досить для дії, що вимагає `needed`."""
        return self.rank >= needed.rank


_PLATFORM_RANK: dict[PlatformRole, int] = {
    PlatformRole.STAFF: 1,
    PlatformRole.ADMIN: 2,
}


class OrganizationKind(StrEnum):
    """Чим є організація для продукту.

    `is_personal` відповідає на інше питання — «чи створена вона разом
    із людиною», — і залишити гостьовий стан на ньому означало б, що
    гостьова організація виглядає як особиста для кожного, хто читає
    цей прапорець. Тому окреме поле.

    `GUEST` існує до того, як зʼявиться людина: анонімна воронка мусить
    комусь належати, а власником у нас завжди є організація. Порожня
    організація дешевша за необовʼязкового власника — інакше кожен
    `WHERE organization_id = :org` отримав би другу гілку, і кожна з
    них була б місцем для витоку між гостями.

    `CLAIMED` — гостьова організація, яку вже привласнили. Стан
    кінцевий: повторне привласнення тієї самої не має ані створити
    другий акаунт, ані перенести ресурси вдруге.
    """

    PERSONAL = "personal"
    TEAM = "team"
    GUEST = "guest"
    CLAIMED = "claimed"

    @property
    def is_guest_funnel(self) -> bool:
        """Чи належить організація анонімній воронці — зараз або в минулому."""
        return self in (OrganizationKind.GUEST, OrganizationKind.CLAIMED)
