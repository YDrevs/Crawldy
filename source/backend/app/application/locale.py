"""Якою мовою говорити з цією людиною просто зараз.

Чиста функція без вводу-виводу: усе, що потрібно, приходить аргументами.
Причина та сама, що й у `retries.py` — правило, від якого залежить кожна
сторінка продукту, має перевірятися без бази.

## Порядок

    явний запит  →  користувач  →  організація  →  англійська

Кожен крок відповідає на своє питання, і саме тому їх чотири, а не два.

**Явний запит** — параметр `?lang=` або мова, вшита в публічне посилання.
Перебиває все: людина сказала прямо.

**Користувач** — його вибір в інтерфейсі. Порожньо означає «не обирав», а
не «обрав англійську»; хто не обирав, поїде за організацією, коли та
змінить мову.

**Організація** — мова, якою складаються звіти, що йдуть далі: керівництву,
клієнтам клієнта. Не збігається з мовою інтерфейсу частіше, ніж здається:
агенція працює українською, а звіт віддає німецькому замовнику.

**Англійська** — канонічна. Не «мова автора продукту», а мова, каталог
якої гарантовано повний.

## Чого тут немає

`Accept-Language` братиметься лише для відвідувача без акаунта — у того,
хто мову налаштував, її не має перебивати браузер. Тому заголовок
приходить сюди як `explicit` лише в тому одному випадку, а не завжди.

**Мови сайту, який аудитують, тут немає взагалі.** Це інша вісь:
іспанський сайт лишається іспанським, хоч би якою мовою відкритий
інтерфейс. Вона живе в `app.audit.vocab` і має інший тип, щоб її не можна
було передати сюди помилково.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.audit.i18n import DEFAULT_LOCALE, LOCALES, Locale, parse


@dataclass(frozen=True, slots=True)
class Resolved:
    """Мова і те, звідки вона взялася.

    Джерело потрібне не для логів: інтерфейс має показувати перемикач
    мови інакше, коли мову вибрали, ніж коли вона дісталася дефолтом.
    """

    locale: Locale
    source: str  # "request" | "user" | "organization" | "default"

    @property
    def rtl(self) -> bool:
        return LOCALES[self.locale].rtl

    @property
    def direction(self) -> str:
        return LOCALES[self.locale].direction


def resolve(
    *,
    requested: str | Locale | None = None,
    user_locale: str | None = None,
    organization_locale: str | None = None,
) -> Resolved:
    """Порядок пріоритетів в одній функції.

    Приймає рядки, а не локалі: усі три джерела приходять із бази або з
    HTTP, тобто нетипізованими. Невідоме значення на будь-якому рівні
    прозоро пропускається далі — зіпсований код мови в профілі не має
    робити продукт непридатним, він має просто нічого не значити.
    """
    for value, source in (
        (requested, "request"),
        (user_locale, "user"),
        (organization_locale, "organization"),
    ):
        locale = value if isinstance(value, Locale) else parse(value)
        if locale is not None:
            return Resolved(locale, source)
    return Resolved(DEFAULT_LOCALE, "default")


__all__ = ["Resolved", "resolve"]
