"""Чи варто пробувати ще раз — і коли.

Політика, а не механізм: чиста функція без вводу-виводу, яку можна
замінити, не чіпаючи ні воркер, ні машину станів квоти. Так само влаштоване
повернення квоти в `billing.refund_policy`, і з тієї самої причини.

Правило одне й неочевидне лише на вигляд: **повторюють те, що могло
змінитися само**.

Недоступний провайдер (PSI віддав 503, браузер не піднявся, модель не
відповіла) — стан зовнішньої системи, і за десять хвилин він інший.
Виняток у нашому коді ділиться навпіл: справжня вада детермінована й
повториться, збій інфраструктури — ні. Один повтор розводить ці два
випадки дешево, тому він є.

Сайт, який не відповів, повторюється теж — і саме тут легко помилитися в
обидва боки. Повтор здається дорогим («ще один краул»), але недосяжний
сайт краулу не коштує взагалі: запит падає на з'єднанні за секунди. А от
не повторювати — дорого: тридцятисекундний збій хостингу перетворюється на
списану квоту, порожній звіт і фальшивий провал у кривій історії. Одне
спостереження в одну мить — слабкий доказ, щоб подавати його як результат.

А от «сайт відмовив» не повторюється: 403 на все — це його рішення, і
повторне питання відрізняє нас від скрапера лише наміром. Скасоване не
повторюється з іншого боку тієї ж причини: скасування — теж рішення.

Вікно повторів навмисно тримається в межах десятків хвилин, а найчастіший
розклад — щодобовий. Інакше повтори одного входження наклалися б на
наступне, і два запуски змагалися б за ту саму квоту.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import timedelta

from app.audit.i18n import DEFAULT_LOCALE, Locale, notice
from app.core.run_enums import FailureClass

# Скільки спроб дозволено кожному класу невдачі — **разом із першою**.
#
#     значення 1  →  одна спроба, жодного повтору
#     значення 2  →  одна початкова + один повтор
#     значення 3  →  одна початкова + два повтори
#
# Це найлегше місце для мовчазної помилки в удвічі: «дві спроби» і «два
# повтори» звучать однаково, а коштують по-різному. Тому число тут одне —
# загальна кількість, — а для другого прочитання є `retries_allowed()`.
#
# Клас, якого тут немає, не повторюється. Це навмисно: додати повтор —
# свідома дія, а не наслідок того, що хтось завів новий клас невдачі й не
# подумав про цей файл.
MAX_ATTEMPTS: dict[FailureClass, int] = {
    FailureClass.SITE_UNREACHABLE: 2,
    FailureClass.PROVIDER_FAILED: 3,
    FailureClass.INTERNAL_ERROR: 2,
}

# Застереження про PROVIDER_FAILED: сьогодні його ніхто не породжує.
# Кожен провайдер — PSI, браузер, модель — ловить власний збій сам і
# перетворює його на деградацію, бо аудит без Core Web Vitals лишається
# аудитом. Рядок тут не мертвий, а на випадок, коли збій провайдера
# справді долетить до рівня запуску: тоді правило вже буде правильним.
#
# Дві спроби для INTERNAL_ERROR, а не три: сюди потрапляють і наші вади,
# і збої інфраструктури. Вада детермінована й повториться, збій — ні,
# тому один повтор розводить їх дешево. Третя спроба коштувала б ще
# одного повного краулу за помилку, яка вже двічі себе показала.

# Перша пауза. Далі множиться на BACKOFF_FACTOR за кожну спробу.
#
# Дві хвилини, а не секунди: майже все, що тут повторюють, — це чужий
# сервіс, який щойно відмовив. Повтор через секунду застане його в тому
# самому стані й лише додасть йому навантаження.
FIRST_DELAY = timedelta(minutes=2)
BACKOFF_FACTOR = 4
MAX_DELAY = timedelta(minutes=30)


@dataclass(frozen=True, slots=True)
class RetryDecision:
    """Рішення разом із причиною.

    Причина — не для логів, а для запису в аудит: клієнт, який дивиться на
    невдалий запуск, має бачити, чому ми не спробували ще раз. «Спроб
    вичерпано» і «такі невдачі не повторюємо» — різні відповіді.
    """

    retry: bool
    delay: timedelta
    reason_key: str
    reason_params: dict[str, object] = field(default_factory=dict)

    @property
    def delay_seconds(self) -> int:
        return int(self.delay.total_seconds())

    def explain(self, locale: Locale = DEFAULT_LOCALE) -> str:
        """Причина мовою читача.

        Політика тексту не пише — вона віддає ключ, як і чек. Поки вона
        повертала готове речення, воно з воркера потрапляло просто в
        журнал спроб і звідти клієнту — українською, хоч би якою мовою
        він читав решту сторінки.
        """
        return notice(self.reason_key, self.reason_params, locale)


_NO = timedelta(0)


def decide(*, failure: FailureClass, attempts: int) -> RetryDecision:
    """`attempts` — скільки спроб уже зроблено, разом із щойно невдалою."""
    allowed = MAX_ATTEMPTS.get(failure)
    if allowed is None:
        return RetryDecision(
            False, _NO, "notice.retry.not_retryable", {"failure": failure.value}
        )
    if attempts >= allowed:
        return RetryDecision(
            False, _NO, "notice.retry.exhausted", {"attempts": attempts, "allowed": allowed}
        )
    return RetryDecision(
        True,
        backoff(attempts),
        "notice.retry.scheduled",
        {"next_attempt": attempts + 1, "allowed": allowed},
    )


def retries_allowed(failure: FailureClass) -> int:
    """Скільки **повторів** дозволено після першої спроби.

    Існує рівно для того, щоб не доводилося тримати в голові, що
    `MAX_ATTEMPTS` рахує спроби цілком.
    """
    return max(MAX_ATTEMPTS.get(failure, 1) - 1, 0)


def backoff(attempts: int) -> timedelta:
    """Пауза перед наступною спробою після `attempts` невдалих.

    Ніколи не нуль. Повтор без паузи — це цикл: воркер бере завдання,
    падає, ставить наступне, бере його ж. Черга при цьому виглядає
    робочою, а сайт клієнта отримує шквал запитів за секунди.
    """
    factor: int = BACKOFF_FACTOR ** max(attempts - 1, 0)
    return min(FIRST_DELAY * factor, MAX_DELAY)


__all__ = [
    "BACKOFF_FACTOR",
    "FIRST_DELAY",
    "MAX_ATTEMPTS",
    "MAX_DELAY",
    "RetryDecision",
    "backoff",
    "decide",
    "retries_allowed",
]
