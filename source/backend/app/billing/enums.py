"""Словник білінгу. Листовий модуль без залежностей."""

from __future__ import annotations

from enum import StrEnum


class SubscriptionStatus(StrEnum):
    """Стан підписки.

    Не булеве `is_paid`: між «платить» і «не платить» лежить усе, через
    що клієнти справді проходять — пробний період, невдале списання,
    пауза, скасування наприкінці періоду.

    `cancel_at_period_end` навмисно не стан, а окремий прапорець: він
    ортогональний до активності, і злиття подвоїло б перелік.
    """

    INACTIVE = "inactive"
    TRIALING = "trialing"
    ACTIVE = "active"
    # Списання не пройшло. Права ще діють — див. GRACE нижче.
    PAST_DUE = "past_due"
    PAUSED = "paused"
    CANCELLED = "cancelled"

    @property
    def grants_entitlements(self) -> bool:
        """Чи дає цей стан права тарифу.

        `past_due` дає — але обмежений час. Відрізати клієнта, який
        платить, на першій невдалій спробі списання гірше, ніж кілька
        днів безкоштовного сервісу: карта протермінувалася, банк
        відхилив разову операцію, людина у відпустці.
        """
        return self in _GRANTING


_GRANTING = frozenset(
    {SubscriptionStatus.TRIALING, SubscriptionStatus.ACTIVE, SubscriptionStatus.PAST_DUE}
)

# Скільки триває грація після невдалого списання — дефолт налаштування
# `billing_past_due_grace_days`. Тут він лише для того, щоб значення мало
# одне джерело; політику визначають налаштування, а не цей рядок.
DEFAULT_PAST_DUE_GRACE_DAYS = 7


class BillingEventStatus(StrEnum):
    """Доля однієї нормалізованої події провайдера.

    «Отримано» і «оброблено» — різні стани навмисно: якщо доменний
    перехід упав після запису події, вона мусить лишитися видимою як
    невдала, придатною до повтору й нездатною створити другий перехід.
    «received = processed» — це модель, у якій збій обробки зникає без
    сліду.
    """

    RECEIVED = "received"
    # Захоплена обробником просто зараз. Окремий стан, а не прапорець:
    # два процеси, що взялися за ту саму подію, розводяться атомарним
    # UPDATE зі зміною статусу — як оренда в планувальника.
    PROCESSING = "processing"
    PROCESSED = "processed"
    # Подія старіша за вже застосований стан. Записана й видима, але не
    # застосована: це не збій, а властивість доставки вебхуків.
    STALE = "stale"
    FAILED = "failed"


class BillingEventKind(StrEnum):
    """Що сталося — нашими словами, не словами провайдера.

    Перекладає адаптер: він знає, що Paddle називає це
    `subscription.payment_failed`, а Stripe — `invoice.payment_failed`.
    Домен знає лише власний словник, і заміна провайдера його не чіпає.
    """

    SUBSCRIPTION_STARTED = "subscription_started"
    SUBSCRIPTION_RENEWED = "subscription_renewed"
    PAYMENT_FAILED = "payment_failed"
    PAYMENT_RECOVERED = "payment_recovered"
    CANCELLATION_SCHEDULED = "cancellation_scheduled"
    SUBSCRIPTION_CANCELLED = "subscription_cancelled"
    SUBSCRIPTION_PAUSED = "subscription_paused"
    SUBSCRIPTION_RESUMED = "subscription_resumed"
    PLAN_CHANGED = "plan_changed"

    # Разова покупка. Окремі види, а не «оплата»: підписка й разова
    # покупка ведуть до різних наслідків — перехід стану проти видачі
    # кредитів, — і об'єднання змусило б розбирати це всередині.
    ONE_OFF_PURCHASED = "one_off_purchased"
    ONE_OFF_REFUNDED = "one_off_refunded"


class PurchaseStatus(StrEnum):
    """Доля разової покупки.

    `PENDING` існує тому, що чекаут і оплата — різні моменти: людина
    може дійти до платіжної сторінки й не заплатити. Кредити зʼявляються
    лише при `PAID`.
    """

    PENDING = "pending"
    PAID = "paid"
    # Касу відкрили й не заплатили, і провайдер це підтвердив. Стан
    # ОБОРОТНИЙ: оплата, що прийде пізніше, оживляє покупку — інакше
    # прибирання зі службового екрана коштувало б клієнту грошей.
    ABANDONED = "abandoned"
    # Кошти повернено. Невикористані кредити цієї покупки відкликаються;
    # уже витрачені лишаються витраченими — послугу було надано.
    REFUNDED = "refunded"


class CreditState(StrEnum):
    """Стан однієї оплаченої одиниці аудиту.

    Переходи роблять умовним UPDATE із перевіркою поточного стану, тож
    подвійний резерв і подвійне списання неможливі: другий запит не
    знайде рядка в очікуваному стані.
    """

    AVAILABLE = "available"
    RESERVED = "reserved"
    CONSUMED = "consumed"
    # Відкликано при поверненні коштів. Не те саме, що витрачено.
    REVOKED = "revoked"


class CommerceModel(StrEnum):
    """Хто юридично продає покупцю.

    Третє поняття поруч із «хто постачає продукт» і «хто провів платіж».
    При merchant of record продавцем виступає сам провайдер: він укладає
    угоду з клієнтом, рахує податок і стоїть у чеку, а ми постачаємо
    йому продукт. При direct провайдер — лише процесор, а продавець ми.

    Живе тут, а не поруч із реєстром юридичних осіб, з тієї ж причини,
    що й решта цього файлу: словник не має залежностей, і таблиці можуть
    на нього посилатися, не тягнучи в шар персистентності бізнес-логіку.
    """

    MERCHANT_OF_RECORD = "merchant_of_record"
    DIRECT = "direct"


class BillingState(StrEnum):
    """Стан оплати одним словом — уже розвʼязаний.

    `SubscriptionStatus` описує підписку, і його недостатньо: «активна,
    але скасована наприкінці періоду» — це `ACTIVE` плюс прапорець, а для
    клієнта це окремий стан із власним текстом. Відсутність підписки він
    не описує взагалі.

    Складати ці два поля в інтерфейсі означало б повторити правило в
    кожному клієнті — вебі, майбутньому мобільному, листі про закінчення
    періоду — і одного дня розійтися в одному з них.
    """

    # Підписки немає. Не помилка: безкоштовний тариф — теж тариф.
    FREE = "free"
    TRIALING = "trialing"
    ACTIVE = "active"
    # Списання не пройшло, права ще діють. Найважливіший стан для тексту:
    # клієнту треба сказати, що робити, поки не пізно.
    PAST_DUE = "past_due"
    PAUSED = "paused"
    # Діє до кінця періоду й не поновиться.
    CANCELLING = "cancelling"
    CANCELLED = "cancelled"
