"""Гроші в мінімальних одиницях і скільки їх у одиниці валюти.

Мінімальна одиниця — не «цент». У єни й вони її немає взагалі (показник
нуль), у динара Бахрейну їх тисяча (показник три). Назва `cents` і
ділення на 100 — те саме припущення в двох місцях, і для міжнародного
продукту воно просто хибне: 4900 єн, поділені на сто, дають 49 єн.

Показник валюти — властивість самої валюти (ISO 4217), а не окремої
ціни. Тому він рахується тут, а не зберігається колонкою: колонка
вимагала б заповнювати очевидне при кожній новій ціні й давала б змогу
заповнити неправильно.
"""

from __future__ import annotations

# Валюти без дробової частини. Сума в них ціла: 4900 JPY — це 4900 єн.
_ZERO: frozenset[str] = frozenset(
    {"BIF", "CLP", "DJF", "GNF", "ISK", "JPY", "KMF", "KRW", "PYG",
     "RWF", "UGX", "UYI", "VND", "VUV", "XAF", "XOF", "XPF"}
)

# Валюти з трьома знаками. 4900 BHD — це 4.900 динара, а не 49.
_THREE: frozenset[str] = frozenset({"BHD", "IQD", "JOD", "KWD", "LYD", "OMR", "TND"})

# Решта світу. Дефолт саме два, а не «невідомо»: невідомий показник
# змусив би сторінку цін мовчати про валюту, якої немає в переліку, —
# гірше, ніж показати її звичним способом.
DEFAULT_EXPONENT = 2


def exponent(currency: str) -> int:
    """Скільки знаків після коми має ця валюта."""
    code = currency.strip().upper()
    if code in _ZERO:
        return 0
    if code in _THREE:
        return 3
    return DEFAULT_EXPONENT


__all__ = ["DEFAULT_EXPONENT", "exponent"]
