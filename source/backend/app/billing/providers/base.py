"""Контракт платіжного провайдера.

Це вся поверхня, яку домен бачить у провайдері. Адаптер (Paddle у
P4.7b, будь-хто інший потім) перекладає своє на це; домен не знає ні
заголовків підпису, ні назв подій, ні схеми payload — і тому заміна
провайдера є заміною адаптера, а не рефакторингом білінгу.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from typing import Any, Protocol

from app.billing.enums import BillingEventKind


class InvalidWebhook(Exception):
    """Вебхук не пройшов перевірки адаптера: підпис, схема, походження.

    Такий запит не стає подією взагалі — його не існує для домену.
    """


class UnhandledEvent(Exception):
    """Підпис дійсний, але цю подію наш потік свідомо не обробляє.

    НЕ підклас `InvalidWebhook`, і це принципово. «Можливо, атака» і
    «ми на це не підписані» вимагають протилежних відповідей: перше —
    відмова, друге — підтвердження, інакше провайдер повторюватиме
    доставку вічно. Один символ для двох станів — та сама помилка, що
    колись дала один `scope` для «жодної сторінки» і «рівно одна».
    """


class ProviderUnavailable(Exception):
    """Провайдер не відповів або відповів помилкою свого боку."""


class Settlement(StrEnum):
    """Чи взяв провайдер гроші за транзакцію — відповідь на пряме питання.

    Це не стан покупки й не право: доступ і далі дає лише перевірена
    подія. Читання потрібне рівно тоді, коли події не буде ніколи, —
    людина закрила касу, не заплативши, і провайдеру нема про що
    повідомляти. Без прямого питання сервер не має як відрізнити
    «передумав» від «заплатив, а подія ще в дорозі», і екран або
    обіцяв би «кошти не списано» тому, хто заплатив, або тримав би в
    очікуванні того, хто передумав.

    `UNKNOWN` — окрема відповідь, а не відсутність відповіді: провайдер
    не відповів, статус нам невідомий, транзакція не наша. Сказати
    «не списано» на підставі тайм-ауту означало б продати другу покупку
    за перші гроші.
    """

    UNPAID = "unpaid"
    PAID = "paid"
    UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class SettlementReport:
    """Що провайдер знає про транзакцію: стан і, якщо називає, гроші.

    Ширше за `Settlement` рівно на те, що потрібно службовій звірці:
    скільки списано насправді й під яким номером квитанція. Наш рядок
    каже, скільки ми хотіли, — а в клієнта на руках сума провайдера.

    Поля грошей необовʼязкові: провайдер, який стану не пояснює, лишає
    їх порожніми, і це чесніше за переписування нашої ж суми.
    """

    settlement: Settlement
    amount_minor: int | None = None
    currency: str | None = None
    invoice: str | None = None
    #: Покупець у провайдера. Для гостьової покупки це єдина його
    #: ідентичність: акаунта в нас він не створював.
    customer_ref: str | None = None
    #: Пошта, якщо провайдер її віддає. Може бути порожньою і тоді, коли
    #: покупець її вказував: право читати покупців — окреме від права
    #: читати транзакції, і мовчання тут означає «ми не бачили», а не
    #: «її немає».
    email: str | None = None


@dataclass(frozen=True, slots=True)
class ProviderRef:
    """Зовнішнє посилання: «як цю річ звати в провайдера».

    Посилання, а не ідентичність: наші обʼєкти живуть під власними id, і
    зміна провайдера міняє посилання, не чіпаючи обʼєктів.
    """

    provider: str
    external_id: str


@dataclass(frozen=True, slots=True)
class CheckoutRequest:
    """Що домен просить у провайдера, щоб відкрити касу.

    `purchase_id` — наш власний ідентифікатор уже створеної покупки в
    стані PENDING. Він і є кореляцією: провайдер поверне його у власних
    даних події, а ми звіримо його зі своїм записом. Дублювати сюди
    аудит, організацію чи знахідки не потрібно — вони вже лежать у
    покупці, і чужому боку їх знати нема за що.

    Для каси ПІДПИСКИ `purchase_id` порожній: покупки-рядка немає, бо
    підписку створює перша ж подія провайдера. Кореляцією тоді служить
    `organization_id`, який адаптер кладе у власні дані транзакції й
    читає назад із подій `subscription.*`.

    Адреси повернення тут немає, і це рішення, а не пропуск. У Paddle
    вона взагалі не серверне поле: сторінку оплати задає обліковий
    default payment link, а куди піти після оплати — каже `successUrl`
    у налаштуваннях Paddle.js, тобто браузер. Поле з такою назвою вже
    один раз спокусило покласти його в `checkout.url`, де воно значить
    геть інше й тихо ламало посилання каси.

    `customer` необовʼязковий навмисно. Анонімна воронка не має ані
    акаунта, ані пошти, а вигадувати синтетичну адресу заради виклику
    `create_customer` означало б створити фальшиву особу заради форми.
    Провайдери, що вміють зібрати покупця на своїй сторінці, збирають.
    """

    purchase_id: uuid.UUID | None
    price_ref: str
    organization_id: uuid.UUID
    customer: ProviderRef | None = None
    email: str | None = None
    # Знижка провайдера для цієї каси. Хто МОЖЕ її отримати — вирішив
    # домен ДО виклику; адаптер лише передає посилання.
    discount_ref: str | None = None


@dataclass(frozen=True, slots=True)
class CheckoutSession:
    """Абстракція оплатної сесії: куди відправити людину платити.

    `ref` — посилання провайдера на транзакцію/сесію. Домен зберігає
    його поруч із покупкою, щоб подія про повернення коштів, яка
    посилається на транзакцію, знайшла свою покупку.
    """

    ref: ProviderRef
    url: str


@dataclass(frozen=True, slots=True)
class VerifiedBillingEvent:
    """Подія, яку адаптер перевірив і переклав на словник домену.

    Єдина форма, у якій події існують за межами адаптера. Поля з
    провайдерською семантикою (`*_ref`) — довідкові рядки; доменні
    рішення приймаються за `kind`, часами й нашими сутностями.

    `occurred_at` — час події **в провайдера**. Саме він вирішує «що
    новіше» при доставці не по порядку; час отримання для цього
    непридатний — він описує нашу мережу, а не історію підписки.
    """

    provider: str
    external_event_id: str
    kind: BillingEventKind
    occurred_at: datetime

    subscription_ref: str | None = None
    customer_ref: str | None = None
    # Прайс провайдера. Домен розвʼязує його в наш Plan через PlanPrice —
    # сам ідентифікатор у бізнес-логіку не потрапляє.
    price_ref: str | None = None

    # Наша організація, якщо адаптер її знає (checkout несе custom-дані).
    # Інакше вона знаходиться за customer_ref через BillingCustomer.
    organization_id: uuid.UUID | None = None

    with_trial: bool = False
    period_start: datetime | None = None
    period_end: datetime | None = None
    trial_end: datetime | None = None
    cancel_at: datetime | None = None

    # Разова покупка. Порожні для подій підписки — у неї кількості немає.
    quantity: int | None = None
    currency: str | None = None
    amount_minor: int | None = None

    payload: dict[str, Any] = field(default_factory=dict)


class BillingProvider(Protocol):
    """Що домен уміє попросити в провайдера.

    Мінімум навмисно: створити покупця, створити оплатну сесію,
    перевірити вебхук. Усе інше — стан підписки, права, періоди — домен
    веде сам за подіями; питати провайдера «а яка зараз підписка» означає
    мати два джерела правди.

    Єдиний виняток — `settlement_of`, і він не про право, а про факт, на
    який події не буде: закрита без оплати каса не породжує нічого. Це
    читання не змінює жодного нашого запису й доступу не дає.

    `create_customer` лишається для потоків, де покупець відомий заздалегідь
    (кабінет, підписка). Разова анонімна покупка крізь нього НЕ йде.
    """

    @property
    def name(self) -> str: ...

    async def create_customer(
        self, *, organization_id: uuid.UUID, email: str
    ) -> ProviderRef: ...

    async def create_checkout(self, request: CheckoutRequest) -> CheckoutSession: ...

    def verify_webhook(
        self, *, headers: dict[str, str], body: bytes
    ) -> VerifiedBillingEvent: ...

    async def settlement_of(self, *, transaction_ref: str) -> Settlement:
        """Чи оплачена транзакція — за словом самого провайдера.

        Провайдер, який не відповів, кидає ProviderUnavailable; викликач
        читає це як UNKNOWN, а не як «не оплачено».
        """
        ...

    async def settlement_report(self, *, transaction_ref: str) -> SettlementReport:
        """Те саме, що `settlement_of`, плюс сума й номер квитанції.

        Існує заради службової звірки: людина, яка зараховує оплату
        вручну, мусить бачити гроші провайдера, а не лише слово «paid».
        Недоступний провайдер кидає ProviderUnavailable — так само.
        """
        ...

    async def create_portal_session(self, *, customer_ref: str) -> str:
        """Свіже посилання на хостований кабінет провайдера.

        Токени сесій не зберігаються і не логуються: посилання живе
        рівно один перехід. Провайдер без порталу кидає
        ProviderUnavailable.
        """
        ...


