"""Що взагалі можна купити — нашими словами, не словами провайдера.

Домен знає рівно одне: «ця покупка відкриває повний вигляд одного
виконаного аудиту». Ані ціни, ані валюти, ані `pri_…` тут немає й бути
не може — інакше зміна провайдера стала б зміною доменної логіки, а
зміна ціни вимагала б релізу.

Відповідність «продукт → прайс провайдера» живе в КАТАЛОЗІ, а не в
конфігурації: закладка «Ціни» задає суму, публікація створює прайс у
провайдера й запамʼятовує його ідентифікатор поруч із записом
(`provider_price_ref`, `provider_product_ref`). Окремого налаштування
«прайс разової покупки» немає навмисно: гість купує ту саму «разову
перевірку», що стоїть на сторінці цін, і ціна в неї одна. Два місця для
однієї суми вже розходились — закладка показувала 9.99, каса брала 10.00.
"""

from __future__ import annotations

import re

from app.core import runtime_config as runtime


def current_provider() -> str:
    """Хто зараз обслуговує касу.

    Один провайдер на встановлення: маршрут вебхука приймає будь-якого
    зареєстрованого — інакше перехід між провайдерами губив би події,
    що вже в дорозі, — але касу відкриває названий тут.
    """
    return (runtime.get("billing_provider") or "fake").strip().lower()


# Форми посилань провайдера. Посилання тепер пише публікація, а не людина,
# тож це не вхідна перевірка, а сторож: запис, у якому під провайдером
# `paddle` лежить не `pri_…`, — зіпсовані дані, і краще побачити це в
# кабінеті, ніж у касі клієнта. Провайдери без записаної форми (фейк у
# тестах) не перевіряються.
_REF_FORMATS: dict[str, dict[str, re.Pattern[str]]] = {
    "paddle": {
        "price": re.compile(r"^pri_[a-z0-9]{10,}$"),
        "discount": re.compile(r"^dsc_[a-z0-9]{10,}$"),
    },
}


def ref_format_problem(provider: str, kind: str, ref: str) -> str | None:
    """Чому посилання не схоже на посилання цього провайдера. None — схоже."""
    pattern = _REF_FORMATS.get(provider.strip().lower(), {}).get(kind)
    if pattern is None or pattern.match(ref):
        return None
    return (
        f"посилання {ref!r} не схоже на {kind}-ідентифікатор "
        f"провайдера {provider}: очікується форма {pattern.pattern}"
    )


__all__ = [
    "current_provider",
    "ref_format_problem",
]
