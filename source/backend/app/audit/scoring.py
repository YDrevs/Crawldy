"""Скоринг: перетворення списку issues на 0..100 по модулях і загальний."""

from __future__ import annotations

from collections.abc import Sequence

from app.audit.types import Issue, Module, Severity

SEVERITY_MULTIPLIER: dict[Severity, int] = {
    Severity.CRITICAL: 5,
    Severity.HIGH: 3,
    Severity.MEDIUM: 2,
    Severity.LOW: 1,
    Severity.INFO: 0,
}

# Півшкала: скільки «штрафних балів» опускає модуль рівно до 50.
#
# Формула гіперболічна: 100 · N / (N + penalty). Вона монотонна й ніколи не
# досягає нуля, тож будь-яке виправлення рухає цифру. Лінійний варіант із
# clamp цього не давав: сайт, що вдвічі перевищує норму, отримував 0 по всіх
# напрямах і лишався на нулі навіть після половини виправлень — тобто
# повторний аудит не показував прогресу, заради якого його й замовляють.
#
# Значення вдвічі менші за старі нормалізатори: так типовий сайт лишається
# на тій самій оцінці, що й раніше (python.org — 52), а поганий перестає
# зливатися в нуль.
MODULE_HALF_SCALE: dict[Module, float] = {
    Module.PERFORMANCE: 30.0,
    Module.SEO: 45.0,
    Module.AI_READY: 30.0,
    Module.LLM_VISIBILITY: 25.0,
    Module.TECH: 20.0,
    # Провалених перевірок доступності на сторінці буває одиниці, а не
    # десятки: Lighthouse дає згорнутий перелік, а не кожне порушення
    # окремо. Тому півшкала менша за решту — інакше три знахідки не
    # зрушили б бал узагалі.
    Module.ACCESSIBILITY: 12.0,
}

# Сума 1.00. Ваги відкалібровано на 969 знімках night3 (сценарій F,
# затверджено 2026-08-31) за принципом обсягу й повторюваності доказу:
#
# * SEO піднято до 0.26 — найглибша сімʼя (32 чеки) і найширший доказ
#   (до 25 відрендерених сторінок), ядро продуктової обіцянки;
# * performance опущено до 0.18 — доказ з ОДНІЄЇ сторінки Lighthouse із
#   задокументованим міжпрогінним шумом (медіана 2 бали overall);
#   односторінкове спостереження не має важити як 25-сторінкове;
# * tech піднято до 0.16 — найширший і найповторюваніший доказ: кожна
#   відповідь сервера, незалежно від контенту;
# * ai_ready 0.16 і llm_visibility 0.14 — сигнали ГОТОВНОСТІ, а не
#   фактичної AI-присутності; наймʼякші розподіли вибірки (медіани
#   77/81, у llm чверть сайтів на 100). Виміряні кореляції між ними
#   слабкі (ρ = −0.05), тож це нормативне рішення про якість доказу,
#   а не декореляція;
# * accessibility лишилась 0.10 свідомо: модуль квантований у чотири
#   значення з однієї сторінки, і чутливість ваги в діапазоні
#   0.06–0.15 зсуває overall максимум на 2–3 бали. Грубість детектора
#   не плутаємо з нормативною важливістю доступності.
#
# Рівні ваги відхилено окремо: при 1/6 сума неконтентних модулів сягає
# порога покриття, і 91 сліпий/withheld аудит отримав би загальний бал
# із perf+tech+a11y — без жодної прочитаної сторінки вмісту.
MODULE_WEIGHT: dict[Module, float] = {
    Module.PERFORMANCE: 0.18,
    Module.SEO: 0.26,
    Module.AI_READY: 0.16,
    Module.LLM_VISIBILITY: 0.14,
    Module.TECH: 0.16,
    Module.ACCESSIBILITY: 0.10,
}

# Одна й та сама проблема на 20 сторінках не має обнуляти модуль.
#
# Було 4×, стало 2×. Причина не в підгонці: 4× досяжні лише там, де
# ми прочитали багато сторінок, а скільки їх прочитано — це частково
# наш бюджет краулу, а не властивість сайту. Сайт на чотири сторінки
# фізично не міг набрати повторень, сайт на двадцять чотири набирав
# їх завжди, і різниця між ними частково вимірювала нас.
#
# Повторення лишається дорожчим за одиничну знахідку — просто вдвічі,
# а не вчетверо. На розширеній вибірці (50 сайтів, 17 у нижньому
# рівні) інверсій стало 12 замість 23, розрив −9 замість −13.
#
# Стеля рахується на `issue_key`, а не на `code`. Поки вона рахувалась на
# коді, «повторенням» вважались і різні проблеми одного детектора:
# `perf.core_web_vitals` покриває LCP, INP, CLS і TTFB, і при критичній
# метриці (вага 4 × 5 = 20 при стелі 20) друга провалена метрика коштувала
# рівно нуль. Сайт з однією критичною метрикою й сайт із трьома отримували
# однакові 60 балів модуля. Стеля існує, щоб приборкати повторення однієї
# проблеми, а не щоб зробити другу безкоштовною.
MAX_PENALTY_PER_KEY = 2.0

# Друга стеля: жоден окремий код не вирішує модуль одноосібно.
#
# Перша стеля відносна — вона обмежує повторення в 4× від самої знахідки,
# і для важкого чека це виходить багато. `ai.jsonld.missing` (вага 4,
# high) дає 12 за штуку, тобто 48 у стелі — при half_scale 30 один цей код
# опускав ai_ready зі 100 до 38. Гірше, що «8 сторінок із 14 без розмітки»
# і «14 з 14» упирались в ту саму стелю й ставали нерозрізненними.
#
# Наслідок був не теоретичний: на калібрувальній вибірці занедбаний сайт
# на WordPress обганяв stripe.com, бо CMS роздає розмітку з коробки, а
# один код вирішував пʼяту частину підсумку. Після цієї стелі інверсій
# рівнів на вибірці не лишилось жодної, а діапазон балів майже не звузився.
#
# Пороги в half_scale модуля, а не в абсолютних балах: модулі мають різну
# чутливість, і спільне число означало б для них різне.
#
# Частку пробували знизити до 0.3 разом із першою стелею: перебір на
# знімках давав 12 інверсій замість 17. Не взято, і причина
# структурна. При 0.3 стеля стає нижчою за одну знахідку важкого чека
# (`ai.jsonld.missing` дає 12 при стелі 9), а `max(worst, ceiling)`
# тоді дорівнює самій знахідці — і повторення не додає нічого взагалі.
# Двадцять сторінок без розмітки коштували б як одна, що прямо
# суперечить призначенню першої стелі. Кращий бал на вибірці не варто
# правила, яке саме себе скасовує.
MAX_PENALTY_SHARE_OF_HALF = 0.5

# Смуги інтерпретації для звітів і UI: верхня межа (виключно) → назва.
BANDS: tuple[tuple[int, str], ...] = (
    (40, "critical"),
    (60, "poor"),
    (80, "medium"),
    (101, "good"),
)


def band(score: int | None) -> str:
    if score is None:
        return "unknown"
    for upper, name in BANDS:
        if score < upper:
            return name
    return BANDS[-1][1]


def penalty(issue: Issue) -> float:
    return issue.weight * SEVERITY_MULTIPLIER[issue.severity]


def module_penalty(issues: Sequence[Issue], module: Module) -> float:
    """Сума штрафів модуля з урахуванням двох стель на один `issue_key`.

    Групування саме за `issue_key` — семантичною проблемою, а не за
    `code` (категорією детектора) і не за `msg` (рядком каталогу).
    Різниця між трьома:

    * `code` занадто грубий: під `perf.core_web_vitals` живуть LCP, INP,
      CLS і TTFB — різні проблеми з різними виправленнями, і ділити для
      них одну стелю означало віддавати другу метрику безкоштовно.
    * `msg` занадто крихкий: це presentation layer, і переформулювання
      тексту мовчки зсувало б бали.

    Стеля рахується від найважчої знахідки групи, а не від останньої
    зустрінутої. Різниця не косметична: коли ліміт брався з поточного
    issue, менш серйозна знахідка, додана до тієї самої групи, **знижувала**
    штраф — сайт із блокуючою вадою доступності мав 57, а сайт із такою
    самою блокуючою плюс ще однією звичайною отримував 67. Результат до
    того ж залежав від порядку перебору.
    """
    # Одиночна знахідка рахується завжди повністю: стеля приборкує
    # повторення, а не силу самої проблеми. Інакше одна критична знахідка
    # у tech (вага 5 × 5 = 25 при half_scale 20) обрізалась би до 10 —
    # і чек, який ловить найгірше, важив би менше за пару дрібних.
    ceiling = MODULE_HALF_SCALE[module] * MAX_PENALTY_SHARE_OF_HALF
    by_key: dict[str, list[float]] = {}
    for issue in issues:
        if issue.module == module:
            by_key.setdefault(issue.issue_key, []).append(penalty(issue))

    total = 0.0
    for values in by_key.values():
        worst = max(values)
        limit = min(worst * MAX_PENALTY_PER_KEY, max(worst, ceiling))
        total += min(sum(values), limit)
    return total


def module_score_raw(issues: Sequence[Issue], module: Module) -> float:
    """Скор до округлення. Завжди в (0, 100], clamp не потрібен.

    Він же використовується для пріоритезації у звіті: різниця тут ніколи
    не вироджується в нуль, тому проблеми можна впорядкувати за важливістю
    навіть на дуже поганому сайті.
    """
    half = MODULE_HALF_SCALE[module]
    return 100.0 * half / (half + module_penalty(issues, module))


def module_score(issues: Sequence[Issue], module: Module) -> int:
    return max(0, min(100, round(module_score_raw(issues, module))))


def active_weights(skipped: set[Module]) -> dict[Module, float]:
    """Ваги модулів, нормалізовані на активні. Пропущений модуль не карається нулем."""
    active = {m: w for m, w in MODULE_WEIGHT.items() if m not in skipped}
    total = sum(active.values())
    return {m: w / total for m, w in active.items()} if total else {}


# Частка ваги, яку треба покрити, щоб загальний бал щось означав.
#
# Перерозподіл ваг доречний, коли бракує одного модуля. Коли бракує трьох
# із пʼяти, він перетворює залишок на фікцію: aequo.ua віддав нашому
# агенту 403, від усього аудиту лишились швидкість (яку міряє Google, і
# його сайт не блокує) та tech — і сайт, про який ми не знаємо нічого,
# отримав 84 бали, другий результат серед 114. Краще не назвати числа,
# ніж назвати таке.
MIN_COVERED_WEIGHT = 0.5


def compute_scores(
    issues: Sequence[Issue], *, skipped_modules: set[Module] | None = None
) -> tuple[int | None, dict[str, int]]:
    """Повертає (overall, {module: score}).

    `overall` — None, якщо покрито менше за `MIN_COVERED_WEIGHT` ваги:
    оцінка за половиною напрямів вводить в оману сильніше, ніж її брак.
    """
    skipped = skipped_modules or set()
    scores = {m.value: module_score(issues, m) for m in Module if m not in skipped}
    covered = sum(w for m, w in MODULE_WEIGHT.items() if m not in skipped)
    if covered < MIN_COVERED_WEIGHT:
        return None, scores
    weights = active_weights(skipped)
    overall = sum(scores[m.value] * w for m, w in weights.items())
    return round(overall), scores


def overall_raw(issues: Sequence[Issue], skipped: set[Module]) -> float:
    """Загальний скор до округлення. Використовує пріоритезація у звіті."""
    return sum(module_score_raw(issues, m) * w for m, w in active_weights(skipped).items())
