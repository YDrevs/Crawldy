#     різні боки цієї межі непорівнянні, і читач історії має це бачити в
#     тому ж полі, у якому дивиться на зміни підрахунку.
# 5 — чек вилучено зі скорингу (13 вересня 2026, G6: E-07). Формула не
#     змінилась ані на константу: ваги модулів, півшкали, стелі, множники
#     й смуги ті самі. Змінився НАБІР чеків — `ai.schema.faq` більше не
#     дає штрафу, тож `ai_ready` зростає рівно на тих сайтах, де він
#     спрацьовував. Це зміна статусу перевірки в скорингу, і канонічний
#     VERSIONING-PLAN вимагає для неї власного покоління.
SCORING_RULES = "5"

# Формат самого набору версій. Змінюється, коли додається чи зникає поле.
VERSIONS_SCHEMA = "1"


def _digest(*parts: Any) -> str:
    payload = "|".join(str(p) for p in parts)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]


def detector_version() -> str:
    """Відбиток набору чеків: коди, ваги, серйозність, модулі, варіанти.

    Саме це вирішує, що потрапить у звіт і скільки коштуватиме. Новий
    чек, знята вага, знижена severity — усе змінює відбиток.

    `variants` тут теж не для повноти: розділити проблеми одного чека
    означає дати кожній власну стелю штрафу, тобто змінити бал, не
    змінивши жодної константи формули.
    """
    from app.audit.checks import REGISTRY

    rows = sorted(
        f"{c.code}:{c.module.value}:{c.severity.value}:{c.weight}:{c.effort.value}"
        f":{','.join(c.variants)}"
        for c in REGISTRY
    )
    return _digest(DETECTOR_RULES, len(rows), *rows)


def scoring_version() -> str:
    """Відбиток формули: покоління правил, ваги, півшкали, стелі, множники, смуги."""
    from app.audit import scoring

    return _digest(
        SCORING_RULES,
        sorted((m.value, w) for m, w in scoring.MODULE_WEIGHT.items()),
        sorted((m.value, h) for m, h in scoring.MODULE_HALF_SCALE.items()),
        scoring.MAX_PENALTY_PER_KEY,
        scoring.MAX_PENALTY_SHARE_OF_HALF,
        scoring.MIN_COVERED_WEIGHT,
        sorted((s.value, m) for s, m in scoring.SEVERITY_MULTIPLIER.items()),
        scoring.BANDS,
    )


def config_version(options: Any) -> str:
    """Відбиток опцій, які впливають на знахідки.

    Мови звіту сюди не входять: вони міняють текст, а не те, що знайдено.
    Модуль-фільтр входить — аудит без performance дає інший бал.
    """
    modules = sorted(m.value for m in (options.modules or ()))
    return _digest(
        options.max_pages,
        options.max_depth,
        sorted(s.value for s in options.strategies),
        modules,
        options.perf_provider,
        options.render,
        options.render_max_pages,
        options.llm,
        options.llm_max_pages,
    )


def audit_versions(options: Any, model: str | None = None) -> dict[str, str | None]:
    """Повний набір для запису поруч з аудитом."""
    return {
        "schema": VERSIONS_SCHEMA,
        "crawler": CRAWLER_VERSION,
        "detector": detector_version(),
        "scoring": scoring_version(),
        "config": config_version(options),
        # Модель, якою реально скористалися. None означає, що семантичного
        # шару не було — і це не те саме, що «модель нічого не знайшла».
        "model": model,
    }


