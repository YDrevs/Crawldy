"""Enum'и домену. Окремий модуль, щоб шар аудиту не залежав від ORM."""

from enum import StrEnum


class AuditStatus(StrEnum):
    """Що сталося із запуском.

    `SKIPPED` окремо від `FAILED` навмисно. «Виконання почалося й
    завершилося невдало» і «виконання не починалося, бо не дозволив
    тариф» — різні відповіді на питання клієнта, і зливати їх означає
    відповідати «зламалося» там, де правильна відповідь «вичерпано».
    Від цього ж залежить, чи є сенс повторювати: скасоване квотою
    повторювати нема чого до нового періоду.

    «Невідомо» станом не є: аудит при цьому виконався, просто бала немає
    (гейт валідності). Це властивість результату, а не запуску, і живе
    вона в `overall_band`.
    """

    QUEUED = "queued"
    RUNNING = "running"
    COMPLETED = "completed"
    PARTIAL = "partial"
    FAILED = "failed"
    # Не виконувався: тариф, квота або політика не дозволили.
    SKIPPED = "skipped"

    @property
    def is_terminal(self) -> bool:
        return self in _TERMINAL

    @property
    def was_executed(self) -> bool:
        """Чи доходило до самої роботи. Пропущений запуск — ні."""
        return self in {AuditStatus.COMPLETED, AuditStatus.PARTIAL, AuditStatus.FAILED}


_TERMINAL = frozenset(
    {
        AuditStatus.COMPLETED,
        AuditStatus.PARTIAL,
        AuditStatus.FAILED,
        AuditStatus.SKIPPED,
    }
)


class Module(StrEnum):
    PERFORMANCE = "performance"
    SEO = "seo"
    AI_READY = "ai_ready"
    LLM_VISIBILITY = "llm_visibility"
    # Захист, аналітика й інфраструктура: security-заголовки, лічильники,
    # захист форм, 404, редиректи. Читається із заголовків відповіді та HTML.
    TECH = "tech"
    # Доступність. Дані з Lighthouse тим самим запитом, що й швидкість:
    # усередині нього axe-core, тож власних правил контрасту ми не пишемо.
    # Окремий напрям, а не частина tech: користувач із порушенням зору —
    # це не питання гігієни сайту, і ховати його серед заголовків сервера
    # означало б, що ніхто його не побачить.
    ACCESSIBILITY = "accessibility"


class Severity(StrEnum):
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class Effort(StrEnum):
    """Скільки коштує впровадити фікс. Ділить impact при пріоритезації."""

    LOW = "low"  # правка в одному місці: файл у корені, рядок у шаблоні
    MEDIUM = "medium"  # правка в шаблоні/CMS, що зачіпає групу сторінок
    HIGH = "high"  # робота з контентом або перебудова рендерингу


class AuditTrigger(StrEnum):
    """Звідки взявся запуск.

    Потрібен не для звітності, а для розбору: «чому цей аудит виконався
    о третій ночі» має відповідь у самому записі, а не в кореляції
    часових міток із таблицею розкладів.
    """

    MANUAL = "manual"
    SCHEDULED = "scheduled"
    API = "api"


class DegradationKind(StrEnum):
    """Чому частина аудиту не виконалася. Йде у звіт як missing_data."""

    COLLECTOR_FAILED = "collector_failed"  # robots/sitemap/llms.txt не зібрано
    CHECK_FAILED = "check_failed"  # окремий чек кинув виняток
    PROVIDER_UNAVAILABLE = "provider_unavailable"  # PSI/Lighthouse не відповів
    MODULE_EXCLUDED = "module_excluded"  # модуль свідомо вимкнено в опціях
    PARTIAL_DATA = "partial_data"  # модуль оцінено, але не на всіх сигналах
    # Необовʼязковий шар (семантика, рендеринг) вимкнено в налаштуваннях.
    #
    # Окремо від PROVIDER_UNAVAILABLE, бо це вибір, а не поломка. Поки
    # обидва означали «збій», аудит без семантичного шару завжди виходив
    # partial — а llm_enabled за замовчуванням False, тож статус
    # completed був недосяжний узагалі: 28 із 35 аудитів валідаційної
    # вибірки були partial без жодної справжньої причини. Поле, яке
    # завжди має одне значення, не несе інформації.
    LAYER_DISABLED = "layer_disabled"


class Confidence(StrEnum):
    """Наскільки твердо ми це стверджуємо.

    Статус відповіді, кількість H1, відсутній заголовок — це факти: тут
    помилитися ніде. Висновок моделі про те, що компанія «ніде не каже,
    де вона», — судження, і воно може бути хибним навіть коли модель
    упевнена.

    Змішувати їх в одному списку без позначки означає обіцяти клієнту
    однакову надійність там, де її немає. Один абсурдний критичний пункт
    коштує довіри дорожче, ніж кілька пропущених дрібних.
    """

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class Verdict(StrEnum):
    """Що сказала людина про знахідку.

    Розділення тут головне. «Не робитимемо» і «неправда» в інтерфейсах
    зазвичай зливаються в одну кнопку «відхилити» — і саме через це
    відхилення нічого не варті як дані: незрозуміло, чек помилився чи
    клієнт не хоче витрачатись. Проти чека свідчить лише WRONG.
    """

    # Знахідка правильна, і її визнали.
    AGREED = "agreed"
    # Знахідка правильна й уже виправлена.
    FIXED = "fixed"
    # Знахідка правильна, але виправляти не будуть: не варте грошей,
    # суперечить іншому рішенню, не пріоритет.
    WONT_FIX = "wont_fix"
    # Знахідки насправді немає: ми помилились. Єдиний вердикт, який щось
    # каже про якість чека.
    WRONG = "wrong"
    # Незрозуміло, що з цим робити. Теж сигнал — але про формулювання,
    # а не про детекцію.
    UNCLEAR = "unclear"


# Вердикти, які свідчать проти чека, а не проти пріоритетів клієнта.
AGAINST_THE_CHECK = frozenset({Verdict.WRONG})

