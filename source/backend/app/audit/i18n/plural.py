"""Форми множини за правилами CLDR — для шести мов каталогу.

Один шаблон `{count} форм` віддає «1 форм», «2 форм» і «21 форм» —
дрібниця, яку помічають усі, і саме та, через яку продукт виглядає
зробленим наспіх. Зовнішньої бібліотеки тут навмисно немає: ядро аудиту
не тягне залежностей заради шести мов, правила яких уміщаються на
екрані.

Категорії — рівно ті, що в CLDR (`one`, `few`, `many`, `other`), і
запис у каталозі має суфікс категорії: `title.one`, `title.few`.
Відсутня форма падає в базовий ключ (`title`), тобто в `other`, — забутий
переклад дає трохи незграбний рядок, а не порожнечу.

Мова приходить рядком (`"uk"`), а не enum-ом: `Locale` живе в
`__init__` пакета, і зворотний імпорт звідси замкнув би коло.
"""

from __future__ import annotations

#: Категорії, які взагалі можуть зʼявитися як суфікс поля каталогу.
PLURAL_FORMS: tuple[str, ...] = ("zero", "one", "two", "few", "many", "other")


def plural_form(locale: str, count: int) -> str:
    """Категорія CLDR для цілого числа цією мовою.

    Українська й російська розрізняють `one` (1, 21, 31…), `few` (2–4,
    22–24…) і `many` (0, 5–20, 25–30…). Французька відносить нуль до
    `one`. Решта мов каталогу мають лише `one` для одиниці.
    """
    code = str(locale).lower()
    n = abs(int(count))
    if code in ("uk", "ru"):
        if n % 10 == 1 and n % 100 != 11:
            return "one"
        if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
            return "few"
        return "many"
    if code == "fr":
        return "one" if n in (0, 1) else "other"
    return "one" if n == 1 else "other"


__all__ = ["PLURAL_FORMS", "plural_form"]
