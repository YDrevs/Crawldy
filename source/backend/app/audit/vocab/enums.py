"""Словник понять розпізнавання. Листовий модуль без залежностей.

Окремо від `__init__`, бо на нього спираються і сам пакет, і файл із
даними — та сама причина, з якої `Module` і `Severity` живуть в
`audit/enums.py`, а не в моделях.
"""

from __future__ import annotations

from enum import StrEnum


class ContentLanguage(StrEnum):
    """Мова вмісту сайту, який аудитують.

    Навмисно **не** `i18n.Locale`, хоч коди й збігаються. Це два різні
    поняття: мова продукту — якою ми говоримо з користувачем, мова вмісту
    — якою написаний чужий сайт. Іспанський сайт лишається іспанським,
    хоч би якою мовою відкритий інтерфейс.

    Збіг значень саме й робить плутанину можливою, а різниця типів робить
    її помилкою перевірки типів, а не тихою вадою в продакшені: сплутані,
    вони змусили б продукт упізнавати сторінки залежно від налаштувань
    інтерфейсу, і сторінка просто ставала б `UNKNOWN`.
    """

    EN = "en"
    ES = "es"
    FR = "fr"
    DE = "de"
    PT = "pt"
    UK = "uk"
    # Російська стоїть тут із тієї ж причини, що й решта: сайт нею пишуть,
    # і без словника його маршрути ми не впізнаємо. Порядок повторює
    # `i18n.Locale` навмисно — читати два переліки різного порядку важче,
    # ніж однакового, а сплутати їх однаково не можна: це різні типи.
    RU = "ru"
    PL = "pl"
    AR = "ar"
    HI = "hi"
    ZH = "zh"
    JA = "ja"


class Concept(StrEnum):
    """Про що сторінка — незалежно від того, якою мовою це написано.

    Поняття, а не слова. Чек питає саме про поняття; те, якими словами
    воно виражається в кожній мові, — справа словника.
    """

    # Де компанії пишуть, хто вони, що продають і як з ними звʼязатися.
    TELLING = "telling"
    # Стрічки, архіви, пагінація: сторінка переказує інші замість того,
    # щоб щось стверджувати.
    ARCHIVE = "archive"
    # Юридичне й службове: ні що продають, ні де вони.
    BOILERPLATE = "boilerplate"
    # Заклик до дії: купити, замовити, звʼязатися.
    CALL_TO_ACTION = "call_to_action"
    # Той самий заклик, але в ТЕКСТІ, який бачить людина, а не в адресі.
    #
    # Окреме поняття, а не ті самі слова: у `CALL_TO_ACTION` лежать
    # ОДНОСЛІВНІ токени шляху, бо `path_words` ріже сегмент по дефісах, а
    # підпис посилання буває фразою («in den warenkorb») і зіставляється
    # початком рядка, а не рівністю. Змішати їх означало б зіпсувати
    # зіставлення адрес заради підписів або навпаки.
    CALL_TO_ACTION_TEXT = "call_to_action_text"


__all__ = ["Concept", "ContentLanguage"]
