"""Ідемпотентна ідентичність збагачення.

Той самий логічний запит для того самого детерміністичного входу мусить
вирішуватись в один збережений результат: повторне відкриття звіту,
повторне завантаження DOCX чи оновлення сторінки не мають права
породити новий платний виклик.

Ідентичність = аудит + тип задачі + версія задачі + версія промпта +
версія схеми + хеш канонічного входу (локаль — частина входу: майбутній
локалізований наратив — це ІНШИЙ кешований результат, а не перезапис
цього).
"""

from __future__ import annotations

import hashlib
import json
from typing import Any


def canonical_json(payload: dict[str, Any]) -> str:
    """Стабільна серіалізація: однаковий вхід — однаковий рядок.

    Ключі сортуються на всіх рівнях, розділювачі без пробілів, юнікод
    не екранується. Це формат для хешу, не для читання.
    """
    return json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def input_hash(payload: dict[str, Any]) -> str:
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()
